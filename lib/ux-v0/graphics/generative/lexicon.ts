export type MotifKind = (typeof MOTIFS)[number];

/** How a motif behaves, so the concept can pair it with a spatial principle and a language that suits it. */
export interface MotifTraits {
  /** 0 straight … 100 curved */
  curvature: number;
  /** 0 loose … 100 rigid */
  rigidity: number;
  /** it wants: a path to follow, a centre to turn about, a zone to fill, an edge to grow from */
  wants: 'path' | 'centre' | 'zone' | 'edge';
  /** one mass (a focal shape) or a field of many small marks */
  mass: boolean;
  /** drawn as lines rather than fills */
  linear: boolean;
}

